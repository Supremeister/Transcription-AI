const assert = require('assert');
const analyzeRouter = require('./src/routes/analyze');
const { runPiAnalysis } = require('./src/services/piAgent');

// Реальный фрагмент контрольной записи №93. В исходном сравнительном экспорте
// были тайм-коды, но не было диаризации, поэтому источник обозначен как «Речь».
const transcript = `[08:52–08:55] Речь:
давайте мы это завтра

[09:10–09:19] Речь:
что конкретно нужно сделать вот нам же не надо определиться с тремя направлениями работы это явно нужно провести анализ

[09:22–09:32] Речь:
нужно не определить цель разбора а нужно найти разрыв между результатом планируемым и ожидаемым

[09:40–09:54] Речь:
посмотри точно ли у тебя там внизу расшита скрипт структура экспертности что такое экспертность

[11:15–11:25] Речь:
тогда давай разведем знание это возможно я не смог ответить на вопросы я не смог правильно донести

[11:31–11:41] Речь:
это коммуникация я не услышал клиента я может и знаю но я другую информацию даю или игнорирую вопросы

[11:50–11:57] Речь:
не пошел я по скрипту да так и пиши исполнение скрипта

[12:36–12:42] Речь:
в общем тут надо знания добавить коммуникацию и стандарты

[13:16–13:23] Речь:
написать конкретные изменения и поставить задачу на следующую неделю

[13:28–13:37] Речь:
по каждой выявленной проблематике сформулировать что нужно делать по-другому

[13:50–14:13] Речь:
может быть это должна быть практика будильник или стикер на мониторе наметить задачи по изменению и как их достичь`;

async function main() {
  const prompt = analyzeRouter._test.buildPiPrompt('tasks', transcript);
  const result = await runPiAnalysis(prompt, {
    thinking: 'low',
    timeoutMs: 180000,
  });

  assert.equal(result.provider, 'openai-codex');
  assert.equal(result.model, 'gpt-5.6-sol');
  assert(/Ответственн/i.test(result.text), 'Нет поля ответственного');
  assert(/явная договорённость|предложение участника|рекомендация аналитика/i.test(result.text), 'Нет типа задачи');
  assert(/\[?(13:16|13:20|13:28|13:50)/.test(result.text), 'Нет тайм-кода основания');
  assert(/конкретн.*изменен|задач.*следующ.*недел/i.test(result.text), 'Потеряна явная задача из фрагмента');

  console.log('✓ Pi разобрал реальный фрагмент записи №93');
  console.log('✓ В задачах есть тип, ответственный и исходный тайм-код');
  console.log(result.text);
}

main().catch(error => {
  console.error(error);
  if (error.details) console.error(error.details);
  process.exit(1);
});
